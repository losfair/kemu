#!/usr/bin/env python3
# Generate kernel/kemu/syscall_table.h: the arm64 (asm-generic) syscall
# numbering dispatched onto x86_64 syscall entry points.
#
# usage: gen-syscalls.py <linux-src> <System.map> <out.h>
import re, sys

src, sysmap, out = sys.argv[1:4]
abis = {"common", "64", "renameat", "rlimit", "memfd_secret"}

# kemu-specific implementations (kernel/kemu/abi.c, signal.c).
overrides = {
    "rt_sigreturn", "clone", "uname", "newfstatat", "fstat",
    "epoll_ctl", "epoll_pwait", "epoll_pwait2", "openat", "openat2",
    "fcntl", "pipe2", "open_by_handle_at", "fanotify_init", "semctl",
}

# Not offered to guests (ENOSYS; programs fall back):
# - io_uring reads and writes native structs (e.g. struct epoll_event for
#   IORING_OP_EPOLL_CTL) behind kemu's back, so the guest ABI can't be
#   guaranteed.
# - rseq compares the host (code-cache) PC against the guest rseq_cs range,
#   so critical sections never abort and a crafted abort_ip would redirect
#   host execution; it is unimplemented (DESIGN §11.2 is aspirational here).
disabled = {"io_uring_setup", "io_uring_enter", "io_uring_register", "rseq"}

syms = set()
for line in open(sysmap):
    parts = line.split()
    if len(parts) == 3:
        syms.add(parts[2])

rows = []
for line in open(f"{src}/scripts/syscall.tbl"):
    line = line.split("#", 1)[0].strip()
    if not line:
        continue
    f = line.split()
    nr, abi, name = int(f[0]), f[1], f[2]
    entry = f[3] if len(f) > 3 else None
    if abi not in abis:
        continue
    rows.append((nr, name, entry))

lines = ["/* SPDX-License-Identifier: GPL-2.0 */",
         "/* Generated by scripts/gen-syscalls.py -- do not edit. */", ""]
decls, cases, missing = [], [], []
maxnr = 0
for nr, name, entry in rows:
    maxnr = max(maxnr, nr)
    if name in overrides:
        fn = f"kemu_sys_{name}"
        decls.append(f"long {fn}(struct pt_regs *regs);")
    elif entry is None or entry == "sys_ni_syscall":
        continue
    elif name in disabled:
        missing.append((nr, name, "disabled"))
        continue
    elif f"__x64_{entry}" in syms:
        fn = f"__x64_{entry}"
        decls.append(f"asmlinkage long {fn}(const struct pt_regs *regs);")
    else:
        missing.append((nr, name, entry))
        continue
    cases.append(f"\tcase {nr}: return {fn}(regs);\t/* {name} */")

lines += sorted(set(decls))
lines += ["", f"#define KEMU_NR_SYSCALLS {maxnr + 1}", "",
          "static long kemu_syscall_table(struct pt_regs *regs, unsigned long nr)",
          "{", "\tswitch (nr) {"]
lines += cases
lines += ["\tdefault: return -ENOSYS;", "\t}", "}", ""]
lines += ["/* arm64 syscalls without an x86_64 entry point, or disabled (ENOSYS): */"]
lines += [f"/*   {nr} {name} ({entry}) */" for nr, name, entry in missing]
open(out, "w").write("\n".join(lines) + "\n")
print(f"{len(cases)} syscalls, {len(missing)} missing:", " ".join(n for _, n, _ in missing))
